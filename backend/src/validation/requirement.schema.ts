import { z } from "zod";
import {
  CREW_ROLES,
  DATE_MODES,
  EVENT_TYPES,
  GENRES,
  LANGUAGES,
  MUSIC_PERFORMER_TYPES,
  PERFORMER_TYPES,
  PLANNER_SERVICES,
  PLANNING_SCOPES,
  SETTINGS,
} from "../constants/options.js";

// ---------- building blocks ----------

const DAY_MS = 24 * 60 * 60 * 1000;

/** "YYYY-MM-DD" that is also a real calendar date (rejects 2026-02-30). */
const isoDate = z
  .string()
  .regex(/^\d{4}-\d{2}-\d{2}$/, "Use the YYYY-MM-DD format")
  .refine((s) => {
    const d = new Date(`${s}T00:00:00Z`);
    return !Number.isNaN(d.getTime()) && d.toISOString().slice(0, 10) === s;
  }, "Not a real date");

const trimmed = (min: number, max: number, label: string) =>
  z
    .string()
    .trim()
    .min(min, `${label} must be at least ${min} characters`)
    .max(max, `${label} must be at most ${max} characters`);

/** Optional free text: empty strings are treated as "not provided". */
const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max, `Keep this under ${max} characters`)
    .optional()
    .transform((v) => (v ? v : undefined));

const budget = z
  .object({
    min: z.number().int().min(0, "Budget cannot be negative").max(100_000_000),
    max: z.number().int().positive("Enter a maximum budget").max(100_000_000),
  })
  .refine((b) => b.max >= b.min, {
    message: "Maximum budget must be at least the minimum",
    path: ["max"],
  });

const notes = optionalText(1000);

// ---------- category-specific details ----------

export const plannerDetailsSchema = z.object({
  planningScope: z.enum(PLANNING_SCOPES),
  guestCount: z.number().int().min(1, "At least 1 guest").max(100_000),
  services: z
    .array(z.enum(PLANNER_SERVICES))
    .min(1, "Pick at least one service")
    .transform((arr) => [...new Set(arr)]),
  budget,
  theme: optionalText(120),
  notes,
});

export const performerDetailsSchema = z
  .object({
    performerType: z.enum(PERFORMER_TYPES),
    genres: z
      .array(z.enum(GENRES))
      .optional()
      .transform((arr) => (arr ? [...new Set(arr)] : undefined)),
    languages: z
      .array(z.enum(LANGUAGES))
      .min(1, "Pick at least one language")
      .transform((arr) => [...new Set(arr)]),
    durationMins: z.number().int().min(15, "At least 15 minutes").max(720, "At most 12 hours"),
    audienceSize: z.number().int().min(1).max(100_000),
    setting: z.enum(SETTINGS),
    soundSystemAvailable: z.boolean(),
    budget,
    notes,
  })
  .superRefine((d, ctx) => {
    const isMusic = (MUSIC_PERFORMER_TYPES as readonly string[]).includes(d.performerType);
    if (isMusic && (!d.genres || d.genres.length === 0)) {
      ctx.addIssue({ code: "custom", path: ["genres"], message: "Pick at least one genre" });
    }
  })
  // Genres are meaningless for e.g. a comedian; drop them rather than store noise.
  .transform((d) =>
    (MUSIC_PERFORMER_TYPES as readonly string[]).includes(d.performerType)
      ? d
      : { ...d, genres: undefined },
  );

export const crewDetailsSchema = z.object({
  roles: z
    .array(
      z.object({
        role: z.enum(CREW_ROLES),
        count: z.number().int().min(1, "At least 1").max(200, "At most 200"),
      }),
    )
    .min(1, "Add at least one role")
    .max(CREW_ROLES.length)
    .refine((roles) => new Set(roles.map((r) => r.role)).size === roles.length, {
      message: "Each role can only be added once",
    }),
  callTime: z.string().regex(/^([01]\d|2[0-3]):[0-5]\d$/, "Use the HH:mm format"),
  hoursPerDay: z.number().min(1, "At least 1 hour").max(24, "At most 24 hours"),
  crewBringsEquipment: z.boolean(),
  budget,
  notes,
});

// ---------- full payload ----------

const basics = {
  // Generated by the client once per form session; makes retries idempotent.
  clientRequestId: z.uuid("clientRequestId must be a UUID"),
  eventName: trimmed(3, 120, "Event name"),
  eventType: z.enum(EVENT_TYPES),
  dateMode: z.enum(DATE_MODES),
  startDate: isoDate,
  endDate: isoDate.nullish(),
  city: trimmed(2, 80, "City"),
  venue: optionalText(160),
};

export const createRequirementSchema = z
  .discriminatedUnion("category", [
    z.object({ ...basics, category: z.literal("planner"), details: plannerDetailsSchema }),
    z.object({ ...basics, category: z.literal("performer"), details: performerDetailsSchema }),
    z.object({ ...basics, category: z.literal("crew"), details: crewDetailsSchema }),
  ])
  .superRefine((d, ctx) => {
    const start = Date.parse(`${d.startDate}T00:00:00Z`);
    if (Number.isNaN(start)) return; // already reported by isoDate

    // One day of slack so a user ahead of UTC (e.g. IST just after midnight)
    // can still pick "today" in their own timezone.
    const todayUtc = Date.parse(new Date().toISOString().slice(0, 10) + "T00:00:00Z");
    if (start < todayUtc - DAY_MS) {
      ctx.addIssue({ code: "custom", path: ["startDate"], message: "Date cannot be in the past" });
    }
    if (start > todayUtc + 2 * 365 * DAY_MS) {
      ctx.addIssue({ code: "custom", path: ["startDate"], message: "Date must be within 2 years" });
    }

    if (d.dateMode === "range") {
      if (!d.endDate) {
        ctx.addIssue({ code: "custom", path: ["endDate"], message: "Pick an end date" });
        return;
      }
      const end = Date.parse(`${d.endDate}T00:00:00Z`);
      if (end <= start) {
        ctx.addIssue({ code: "custom", path: ["endDate"], message: "End date must be after the start date" });
      } else if (end - start > 30 * DAY_MS) {
        ctx.addIssue({ code: "custom", path: ["endDate"], message: "Events can span at most 30 days" });
      }
    }
  })
  // A single-day event never stores an end date, even if the client sent one.
  .transform((d) => (d.dateMode === "single" ? { ...d, endDate: undefined } : d));

export type CreateRequirementInput = z.infer<typeof createRequirementSchema>;

// ---------- query params ----------

export const listQuerySchema = z.object({
  category: z.enum(["planner", "performer", "crew"]).optional(),
  page: z.coerce.number().int().min(1).default(1),
  limit: z.coerce.number().int().min(1).max(50).default(20),
});
